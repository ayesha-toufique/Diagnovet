"""Models for Assessment Inputs and Structured Clinical Outputs."""
from dataclasses import dataclass, field
from typing import List, Dict, Any, Optional
from backend.models.condition import EvidenceMatch


@dataclass
class PetProfile:
    """Pet demographic details for the active session."""
    species: str  # "Dog" or "Cat"
    breed: str
    gender: str
    age: float
    weight: Optional[float] = None
    background: str = ""


@dataclass
class AssessmentInput:
    """Clinical assessment inputs collected during the guided consultation."""
    pet: PetProfile
    symptoms: List[str] = field(default_factory=list)
    answers: Dict[str, str] = field(default_factory=dict)
    duration: str = ""
    severity: str = ""
    frequency: str = ""
    emergency_answers: Dict[int, str] = field(default_factory=dict)


@dataclass
class DecisionOutcome:
    """Structured veterinary care decision outcome."""
    icon: str
    name: str
    tone: str   # "red", "amb", "blu", "grn"
    level: str  # "Critical", "High", "Medium", "Low"
    text: str
    steps: List[str] = field(default_factory=list)
    rationale: str = ""


@dataclass
class AssessmentResult:
    """Comprehensive Assessment Result generated by the inference engine and DSS."""
    pet: PetProfile
    matches: List[EvidenceMatch]
    emergency_detected: bool
    emergency_reasons: List[str]
    decision_index: int
    decision: DecisionOutcome
    supporting_findings: List[str]
    contradictory_findings: List[str]
    missing_information: List[str]
    table_rows: List[Dict[str, Any]]
    disclaimer: str = (
        "Diagnovet provides decision support only and is not a definitive veterinary diagnosis. "
        "Consult a qualified veterinarian for clinical examination, diagnosis, and prescription."
    )
